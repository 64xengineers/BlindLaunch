import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Contracts whose ABIs the keeper and the web app use, from `forge build` output. */
const contracts = [
  ["BlindAuctionV2", "blindAuctionV2Abi"],
  ["KeeperRegistry", "keeperRegistryAbi"],
  ["MarketSeeder", "marketSeederAbi"],
  ["TokenFactory", "tokenFactoryAbi"],
  ["TestToken", "testTokenAbi"],
] as const;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");
const target = resolve(here, "../src/generated.ts");

export function render(): string {
  const parts = contracts.map(([name, exportName]) => {
    const artifact = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), "utf8")) as { abi: unknown };
    return `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  });
  return `// Generated by packages/abi/scripts/generate.ts from contracts/out. Do not edit; run \`pnpm --filter @blindlaunch/abi generate\` after \`forge build\`.\n\n${parts.join("\n")}`;
}

const rendered = render();
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== rendered) {
    console.error("packages/abi/src/generated.ts is stale: run `forge build` then `pnpm --filter @blindlaunch/abi generate`.");
    process.exit(1);
  }
  console.log("ABIs up to date");
} else {
  writeFileSync(target, rendered);
  console.log(`wrote ${target}`);
}
